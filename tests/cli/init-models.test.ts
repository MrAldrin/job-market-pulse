test("metadata unavailable preserves committed choices only when kept and requires effort for a new model", () => {
  const edit = (answers: TomlTable, replies: readonly string[], detect = () => Effect.succeed<readonly (typeof pi | typeof claude)[]>([pi, claude])) => run({
    original: saved, input: {
      ...named(answers), answers: { ...defaults, ...answers }, committedDefaults: defaults,
      advanced: true, recoveryStep: "reviewer",
    }, replies, services: { query: null, detect },
  });

  const retained = edit({ ai_setup: "separate" }, Array<string>(12).fill(""));
  expect(Either.getOrThrow(retained.result)).toBe(saved);
  const changed = edit({ judge_model: "test/new" }, ["", "xhigh"]);
  expect(models(changed.result).judge.effort).toBe("xhigh");
  expect(changed.stdout).not.toContain("current: minimal");
  const differentHarness = edit({ judge_harness: "claude-code" }, ["alias", "low"]);
  expect(models(differentHarness.result).judge).toMatchObject({ harness: "claude-code", model: "alias", effort: "low" });
  expect(differentHarness.stdout).not.toContain("current: test/judge");
  expect(differentHarness.query).not.toHaveBeenCalled();
});

