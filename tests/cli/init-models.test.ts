test.each([true, false])("both metadata parsers enforce the UTF-8 byte limit (oversized: %s)", (oversized) => {
  const output = (text: string): string => {
    const remaining = runStdoutLimit - Buffer.byteLength(text);

    return text + "ø".repeat(Math.floor(remaining / 2)) + " ".repeat(remaining % 2) + (oversized ? "ø" : "");
  };

  const actual = run({ replies: ["Pi", "test/typed", "minimal", "low"], services: { query: (argv) => Effect.succeed({
    kind: "ok", text: output(argv.includes("--help") ? `${help}\n\n` : `${listing}\n`),
  }) } });

  expect(actual.query.mock.calls).toEqual([[ [...piOptions, "--list-models"] ], [ [...piOptions, "--help"] ]]);
  expect(actual.stdout.includes("1. test/listed")).toBe(!oversized);
  expect(actual.stdout.includes("Pi model list failed.")).toBe(oversized);
  expect(actual.stdout.includes("does not advertise minimal")).toBe(!oversized);
  expect(actual.stdout).not.toContain("ø");
  expect(models(actual.result).judge.effort).toBe(oversized ? "minimal" : "low");
});

