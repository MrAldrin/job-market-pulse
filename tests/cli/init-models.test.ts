test("fresh plans, rejected invalid selections and cancellation do not touch disk", () => {
  const root = mkdtempSync(join(tmpdir(), "pulse-model-plan-"));
  const path = join(root, "models.toml");

  try {
    const fresh = run({ input: named({ ai_setup: "common", ai_program: "pi", ai_model: "test/typed", ai_effort: "high" }) });
    expect(models(fresh.result).judge.model).toBe("typed");
    expect(readdirSync(root)).toEqual([]);
    const input = named({ ai_setup: "common", ai_program: "pi" });
    const missing = run({ input: { ...input, answers: { ...input.answers, ai_model: "test/current" }, nonInteractive: true } });
    expect(missing.result).toMatchObject({ left: new InitMissingAnswer({ key: "ai_effort" }) });
    expect(missing.answers.ai_model).toBe("test/current");
    expect(missing.answers.ai_effort).toBeUndefined();
    expect(missing.answers.judge_effort).toBeUndefined();
    expect(missing.ask).not.toHaveBeenCalled();
    expect(missing.query).not.toHaveBeenCalled();
    expect(readdirSync(root)).toEqual([]);
    writeFileSync(path, saved);
    const original = readFileSync(path, "utf8");
    const invalid = run({ original, input: named({ ai_setup: "invented" }) });
    const cancelled = run({ original, input: { recoveryStep: "reviewer" }, replies: ["3", "3", "3"] });
    expect(invalid.result).toMatchObject({ left: expect.any(InitInputError) });
    expect(cancelled.result).toMatchObject({ left: new InterviewCancelled({ message: "Too many invalid answers." }) });
    expect(readFileSync(path, "utf8")).toBe(saved);
    expect(readdirSync(root)).toEqual(["models.toml"]);
  } finally {
    rmSync(root, { recursive: true, force: true });
  }
});

