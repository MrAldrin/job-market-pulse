test("explicit common suppresses recovered model and effort even when a stage names a different harness", () => {
  const common = { ai_common: "yes", ai_program: "pi", ai_model: "test/new", ai_effort: "low", judge_harness: "claude-code" };
  const recovered = { judge_harness: "claude-code", judge_model: "old-alias", judge_effort: "high" };

  const edit = (answers: TomlTable, replies: readonly string[], nonInteractive = false) => run({
    original: saved, input: {
      ...named(answers), answers: { ...defaults, ...recovered, ...answers }, committedDefaults: defaults,
      recoveredKeys: new Set(Object.keys(recovered)), nonInteractive,
    }, replies, services: { query: null, detect: () => Effect.succeed([pi, claude]) },
  });

  const typed = edit(common, ["new-alias", "xhigh"]);
  expect(typed.ask).toHaveBeenCalledTimes(2);
  expect(typed.ask).toHaveBeenNthCalledWith(1, "Model: ");
  expect(typed.ask).toHaveBeenNthCalledWith(2, "Effort: ");
  expect(models(typed.result).judge).toMatchObject({ harness: "claude-code", model: "new-alias", effort: "xhigh" });
  expect(typed.stdout).not.toContain("old-alias");
  expect(typed.query).not.toHaveBeenCalled();
  const missingModel = edit(common, [], true);
  expect(missingModel.result).toMatchObject({ left: new InitMissingAnswer({ key: "judge_model" }) });
  const missingEffort = edit({ ...common, judge_model: "named-alias" }, [], true);
  expect(missingEffort.result).toMatchObject({ left: new InitMissingAnswer({ key: "judge_effort" }) });
  const explicit = edit({ ...common, judge_model: "named-alias", judge_effort: "minimal" }, [], true);
  expect(explicit.ask).not.toHaveBeenCalled();
  expect(models(explicit.result).judge).toMatchObject({ harness: "claude-code", model: "named-alias", effort: "minimal" });
});

